    def show_section(
        self,
        index
    ):

        if index < 0:

            return

        titles = list(
            self.sections.keys()
        )

        if index >= len(
            titles
        ):

            return

        self.text.setHtml(
            self.sections[
                titles[index]
            ]
        )

    # ==================================================
    # ПОИСК
    # ==================================================

    def filter_sections(
        self,
        text
    ):

        text = (
            text
            .lower()
            .strip()
        )

        for index in range(
            self.menu.count()
        ):

            item = self.menu.item(
                index
            )

            visible = (
                text
                in
                item.text().lower()
            )

            item.setHidden(
                not visible
            )

        # Если текущий пункт скрыт,
        # автоматически выбираем первый видимый.

        current = self.menu.currentItem()

        if current and not current.isHidden():

            return

        for index in range(
            self.menu.count()
        ):

            item = self.menu.item(
                index
            )

            if not item.isHidden():

                self.menu.setCurrentRow(
                    index
                )

                break